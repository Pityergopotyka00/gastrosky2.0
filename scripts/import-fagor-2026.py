#!/usr/bin/env python3
"""Import individual, model-numbered products from Fagor's official 2026 PDF.

Input: text generated by pdftotext -raw AND pdftotext -layout for the same PDF.
Only rows with an explicit 8-digit Fagor article code and a plausible adjacent
MODEL are included. No guessed products, prices, stock, images, or specifications.
"""
from __future__ import annotations
import json
import os
import re
import sys
from collections import Counter
from pathlib import Path

CATALOGUE = "https://www.fagorprofessional.com/documents/d/global/catalogue-foodservice-en-export-1"
PRODUCT_PATH = Path("data/catalog-products.json")
HTML_PATH = Path("index.html")
REPORT_PATH = Path("data/fagor-import-report.json")
CODE = re.compile(r"(?<!\d)(1[89]\d{6})(?!\d)")
MODEL = re.compile(r"(?=.*[A-Z])(?=.*\d)[A-Z0-9][A-Z0-9 ./+()×,_-]{1,48}$")
HEADERS = re.compile(r"\b(?:MODEL|CODE|PRICE|VOLTAGE|DIMENSIONS|CAPACITY|POWER|DEPTH|WIDTH|HEIGHT|PAGE|FAGOR PROFESSIONAL|FOODSERVICE|INDEX|REF\.|QUANTITY)\b", re.I)
EXCLUDE = re.compile(r"^[\d\s.,x×/+()-]+$|^(?:GN|EN)\s+\d/\d$|^\d+V\b|^\d+\s*Hz", re.I)
GROUPS = [
    (0, 120, "Főzőberendezések", "Cooking"),
    (120, 170, "Sütők és sütőtartozékok", "Ovens"),
    (170, 246, "Mosogatástechnika", "Warewashing"),
    (246, 384, "Hűtéstechnika", "Commercial refrigeration"),
    (384, 430, "Ételkiosztó és tálalórendszerek", "Distribution"),
    (430, 520, "Rozsdamentes konyhai bútorok", "Static preparation"),
    (520, 999, "Elszívástechnika", "Extraction"),
]
STOP_WORDS = set(("A AN THE WITH WITHOUT FOR STANDARD NEW ELECTRIC GAS MODEL CODE REF REFERENCES "
                  "DIMENSIONS TEMPERATURE TOTAL POWER CAPACITY WASHING COOKING PROFESSIONAL FRICTION "
                  "ACCESSORIES FOOD SERVICE FOODSERVICE EUROPE KITCHEN STAINLESS STEEL GENERAL "
                  "INCLUDED PRICE TABLES OPTION FREQ FREQUENCY").split())

def category(page: int) -> tuple[str, str]:
    for low, high, hu, en in GROUPS:
        if low <= page < high:
            return hu, en
    return "Nagykonyhai berendezések", "Foodservice"

def valid_model(candidate: str) -> bool:
    value = candidate.strip().strip(" -:;•\t")
    if not (2 <= len(value) <= 48) or not MODEL.fullmatch(value):
        return False
    if HEADERS.search(value) or EXCLUDE.search(value):
        return False
    words = re.findall(r"[A-Z]{2,}", value)
    if words and all(word in STOP_WORDS for word in words):
        return False
    if not re.search(r"[A-Z][A-Z0-9-]*\d|\d[A-Z]", value):
        # For example, a plain sentence containing a size in millimetres.
        return False
    if len(value.split()) > 5:
        return False
    return True

def candidates_for_code(lines: list[str], ix: int, code: str) -> list[str]:
    found = []
    line = lines[ix]
    left = line.split(code, 1)[0].strip()
    # In -layout mode Fagor frequently has "MODEL   ...   19123456  ...".
    if left:
        # Leading price/dimension columns are not product names.
        chunks = re.split(r"\s{2,}", left)
        for chunk in reversed(chunks[-3:]):
            if valid_model(chunk):
                found.append(chunk)
    # In -raw mode table cells are on consecutive lines: MODEL then CODE.
    for steps in (1, 2):
        if ix < steps:
            break
        previous = lines[ix - steps].strip()
        if CODE.search(previous) or len(previous) > 54:
            break
        if valid_model(previous):
            found.append(previous)
    # Some official tables print article CODE before the MODEL column.
    # Accept only an immediately adjacent model; never scan an entire page.
    for steps in (1, 2):
        target = ix + steps
        if target >= len(lines):
            break
        subsequent = lines[target].strip()
        if CODE.search(subsequent) or len(subsequent) > 54:
            break
        if valid_model(subsequent):
            found.append(subsequent)
    return found

def read_pdf_text(path: str) -> list[str]:
    return Path(path).read_text(encoding="utf-8", errors="replace").split("\f")

def gather(paths: list[str]) -> dict[str, dict]:
    matches: dict[str, dict] = {}
    for path in paths:
        pages = read_pdf_text(path)
        for page_num, content in enumerate(pages, start=1):
            lines = [line.strip() for line in content.splitlines() if line.strip()]
            # Only parse model/code tables. Captions containing a random 8-digit
            # reference cannot independently create a public storefront item.
            for index, line in enumerate(lines):
                codes = CODE.findall(line)
                if not codes or len(codes) > 3:
                    continue
                nearby = " ".join(lines[max(0,index-90):index+1]).upper()
                if "CODE" not in nearby and "REFERENCE" not in nearby and "REF." not in nearby:
                    continue
                for code in codes:
                    options = candidates_for_code(lines, index, code)
                    if not options:
                        continue
                    model = options[0]
                    # Discard model names which are really a voltage or size value.
                    if not valid_model(model):
                        continue
                    confidence = 3 if code in line and model in line else 2
                    old = matches.get(code)
                    if old is None or confidence > old["confidence"]:
                        matches[code] = {
                            "model": model, "page": page_num,
                            "confidence": confidence,
                            "text_source": os.path.basename(path),
                            "evidence": line[:160],
                        }
    return matches

def main() -> int:
    if len(sys.argv) < 3:
        print("Usage: python3 scripts/import-fagor-2026.py /tmp/fagor.raw.txt /tmp/fagor.layout.txt", file=sys.stderr)
        return 2
    matches = gather(sys.argv[1:])
    products = json.loads(PRODUCT_PATH.read_text(encoding="utf-8"))
    existing_ids = {p["id"] for p in products}
    proposed = []
    for code, result in sorted(matches.items()):
        product_id = "fagor:" + code
        if product_id in existing_ids:
            continue
        model = result["model"]
        page = result["page"]
        section, section_en = category(page)
        proposed.append({
            "id": product_id,
            "manufacturer": "Fagor",
            "supplier": "Fagor Professional",
            "sku": code,
            "model": model,
            "name": "Fagor Professional " + model + " – " + section,
            "category": section,
            "description": ("Fagor Professional " + model + " – a gyártó 2026-os hivatalos "
                            "nagykonyhai katalógusában " + code + " cikkszámmal "
                            "szereplő termék. Kérj személyre szabott ajánlatot; a pontos "
                            "műszaki kivitel, ár és szállítási lehetőség egyeztetés alapján."),
            "specifications": {
                "Gyártói modell": model, "Gyártói cikkszám": code,
                "Katalógus": "Fagor Professional Foodservice 2026",
                "Katalógusoldal (PDF)": str(page)
            },
            "source_url": CATALOGUE + "#page=" + str(page),
            "source_type": "manufacturer_2026_pdf_model_code",
            "record_status": "official_pdf_model_code_review_manufacturer_availability",
            "price": None, "availability": None,
            "image_url": None, "photo_status": "product_photo_pending",
            "stock_source_status": "supplier_stock_unverified",
        })
    fagor_total = sum(p["manufacturer"] == "Fagor" for p in products) + len(proposed)
    report = {
        "catalogue": CATALOGUE,
        "extracted_distinct_article_codes": len(matches),
        "new_records": len(proposed),
        "fagor_total_if_published": fagor_total,
        "sample": [{"code": code, **data} for code,data in list(matches.items())[:20]],
        "sections": dict(Counter(p["category"] for p in proposed)),
        "note": "Model/code pairs extracted from official manufacturer PDF; require dealer assortment confirmation.",
    }
    REPORT_PATH.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({k:v for k,v in report.items() if k!="sample"}, ensure_ascii=False, indent=2))
    min_count = int(os.environ.get("FAGOR_MIN_TOTAL", "200"))
    if fagor_total < min_count:
        print("REFUSING to publish: not enough verified model/code records to reach "+str(min_count), file=sys.stderr)
        return 1
    products.extend(proposed)
    PRODUCT_PATH.write_text(json.dumps(products, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    html = HTML_PATH.read_text(encoding="utf-8")
    marker = "let products="
    a = html.find(marker)
    b = html.find(";\nconst search=", a)
    if a < 0 or b < 0:
        raise ValueError("embedded catalogue in storefront not found")
    # Keep the initial HTML light. The page fetches the complete JSON as soon
    # as it loads; embedded products are just the offline fallback.
    embedded = json.dumps(products[:300], ensure_ascii=False, separators=(",",":")).replace("<", "\\u003c")
    html = html[:a] + marker + embedded + html[b:]
    import re
    html, count = re.subn(
        r'(<a class="gs-intro-brand" href="#termekek" data-brand-filter="Fagor"><strong>FAGOR</strong><span>)\d+( termék megtekinthető</span>)',
        lambda m: m.group(1)+str(fagor_total)+m.group(2), html
    )
    if count != 1:
        raise ValueError("Fagor brand count label not found")
    HTML_PATH.write_text(html, encoding="utf-8")
    print("Published",len(proposed),"new Fagor entries; total",fagor_total)
    return 0

if __name__ == "__main__":
    sys.exit(main())
